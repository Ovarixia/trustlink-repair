const ACTOR = COMPROMISED.id;

function fx(
  mutationId: string,
  tenant: Effect["tenant"],
  suffix: string,
  summary: string,
  classification: Effect["classification"],
  rationale: string,
  residualRisk?: string,
): Effect {
  return {
    id: `eff-${mutationId}-${suffix}`,
    mutationId,
    tenant,
    summary,
    classification,
    rationale,
    residualRisk,
  };
}

